"""Check Git candidates or staged blobs without printing private file contents."""
from __future__ import annotations

import argparse
import fnmatch
import json
import re
import subprocess
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from cq_patch_1031 import LFS_POINTER_PREFIX, payload_guard  # noqa: E402
MAX_SOURCE_BYTES = 2 * 1024 * 1024
PRIVATE_DIRS = {
    "input", "data", "datasets", "artifacts", "_stage", "_scratch", "encoders",
    "pretrained", "models", "checkpoints", "source_snapshot", ".local_notebook_backups",
    "__pycache__", ".ipynb_checkpoints", ".pytest_cache", ".cache", ".venv", "venv", ".aws", ".ssh",
}
PRIVATE_PREFIXES = ("final_quality", "phase_features", "weighted_loqv", "fullA", "fulltrain_a", "cq_v4",
                    "private_d06", "_github_incident")
PUBLIC_DOCUMENTS = {
    "DATA_CARD_V4_2.md",
    "GITHUB_REVIEW_2026_10_31.md",
    "BANG_GIAI_TRINH_CONG_THUC_FEATURE_VA_NHAN_CQ_V4_2026_10_23.md",
}
# These IDs are generated by the tiny in-memory/temporary test fixtures, not
# copied from the research dataset. Other IDs and file paths remain checked.
SYNTHETIC_LEARNER_NUMBERS = {
    "test_cq_tempo_features.py": {1, 2},
    "tests/test_cq_v4_2_builder.py": {1, 4},
}
SECRET_PATTERNS = {
    "private-key marker": re.compile(r"-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----"),
    "AWS access-key pattern": re.compile(r"\b(?:AKIA|ASIA)[A-Z0-9]{16}\b"),
    "GitHub token pattern": re.compile(r"\b(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,})\b"),
    "API-key pattern": re.compile(r"\bsk-(?:proj-)?[A-Za-z0-9_-]{30,}\b"),
    "literal learner ID": re.compile(r"\bU_\d+\b"),
}


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT)


def path_problem(name):
    path = PurePosixPath(name)
    if name == "afelo_sentiment_cardiff/requirements-sentiment.txt":
        return None
    if name == "17_eda_final_quality_v2.ipynb":
        return "private example notebook; publish its Python implementation instead"
    if any(p in PRIVATE_DIRS or p.startswith(PRIVATE_PREFIXES) for p in path.parts[:-1]):
        return "dataset/cache/output directory"
    if path.name in {".gitignore", "pyproject.toml"}:
        return None
    if name in {".gitattributes", "README.md", "GITHUB_CODE_ONLY.md", "HANDOFF.md"}:
        return None
    if name in PUBLIC_DOCUMENTS:
        return None
    if fnmatch.fnmatchcase(path.name, "requirements*.txt"):
        return None
    if path.suffix in {".py", ".ipynb", ".sh"}:
        return None
    return "outside the code-only file allowlist"


def content_problems(name, payload):
    errors = [reason for _, reason in payload_guard({name: payload})["problems"]]
    if PurePosixPath(name).name == ".gitattributes":
        errors.extend(reason for _, reason in payload_guard(
            {}, payload.decode("utf-8", errors="replace"))["problems"])
    try:
        source = payload.decode("utf-8")
    except UnicodeDecodeError:
        return ["not UTF-8 source text"]
    if "\0" in source:
        return ["binary content in a source file"]
    for label, pattern in SECRET_PATTERNS.items():
        if label == "literal learner ID":
            synthetic_ids = {f"U_{n}" for n in SYNTHETIC_LEARNER_NUMBERS.get(name, set())}
            if set(pattern.findall(source)) - synthetic_ids:
                errors.append(label)
        elif pattern.search(source):
            errors.append(label)
    if name.endswith(".ipynb"):
        try:
            notebook = json.loads(source)
            cells = notebook["cells"]
            if any(c.get("outputs") or c.get("execution_count") is not None for c in cells if c.get("cell_type") == "code"):
                errors.append("notebook has outputs/execution counts; run scripts/clear_notebook_outputs.py")
            if any(c.get("attachments") for c in cells):
                errors.append("notebook contains embedded attachments")
            if notebook.get("metadata", {}).get("widgets"):
                errors.append("notebook contains widget state")
        except (ValueError, KeyError, TypeError):
            errors.append("invalid notebook JSON/schema")
    return errors


def repository_payload_problems(repo, treeish=None, working_tree=False):
    """Inspect the whole repo, including root and nested .gitattributes.

    Read only blob headers except for attribute files. Pipeline source content
    and its stricter path allowlist are checked separately. No checkout, LFS
    download, or dataset parsing is performed, even with --tree.
    """
    def run(*args):
        return subprocess.check_output(["git", *args], cwd=repo)

    if treeish is not None:
        entries = []
        for entry in run("ls-tree", "-r", "-z", treeish).split(b"\0"):
            if not entry:
                continue
            meta, name = entry.split(b"\t", 1)
            mode, kind, oid = meta.decode().split()
            entries.append((name.decode(), mode, oid if kind == "blob" else None))
    elif working_tree:
        names = run("ls-files", "--cached", "--others", "--exclude-standard", "-z")
        entries = [(name.decode(), None, None) for name in names.split(b"\0") if name]
    else:
        entries = []
        for entry in run("ls-files", "--stage", "-z").split(b"\0"):
            if not entry:
                continue
            meta, name = entry.split(b"\t", 1)
            mode, oid, stage = meta.decode().split()
            entries.append((name.decode(), mode if stage == "0" else "unmerged", oid))

    errors = []
    for name, mode, oid in entries:
        path = repo / name
        if working_tree:
            if not path.exists() and not path.is_symlink():
                continue
            regular = path.is_file() and not path.is_symlink()
        else:
            regular = mode in {"100644", "100755"}
        if not regular:
            errors.append((name, "non-regular or unmerged repository entry"))
            continue
        errors.extend(payload_guard({name: b""})["problems"])
        if working_tree:
            with path.open("rb") as stream:
                head = stream.read(len(LFS_POINTER_PREFIX))
        else:
            with subprocess.Popen(["git", "cat-file", "blob", oid], cwd=repo,
                                  stdout=subprocess.PIPE, stderr=subprocess.DEVNULL) as proc:
                head = proc.stdout.read(len(LFS_POINTER_PREFIX))
                proc.stdout.close()
                if proc.poll() is None:
                    proc.terminate()
                proc.wait()
        if head == LFS_POINTER_PREFIX:
            errors.append((name, "con trỏ Git LFS"))
        if PurePosixPath(name).name == ".gitattributes":
            data = path.read_bytes() if working_tree else run("cat-file", "blob", oid)
            rules = payload_guard({}, data.decode("utf-8", errors="replace"))
            errors.extend((f"{name}:{location.rsplit(':', 1)[-1]}", reason)
                          for location, reason in rules["problems"])
    return sorted(set(errors)), len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--working-tree", action="store_true", help="Check files Git would allow, before staging")
    mode.add_argument("--staged", action="store_true", help="Check actual index blobs, including force-added files (default)")
    mode.add_argument("--tree", metavar="COMMIT", help="Read a committed tree without checkout or LFS downloads")
    args = parser.parse_args()
    repo = Path(git("rev-parse", "--show-toplevel").decode().strip())
    prefix = ROOT.relative_to(repo).as_posix()
    prefix = "" if prefix == "." else prefix + "/"
    errors, repo_count = repository_payload_problems(repo, args.tree, args.working_tree)
    if args.tree:
        output = git("ls-tree", "-r", "--name-only", "-z", args.tree, "--", ".")
        names = [n for n in output.decode().split("\0") if n]
    elif args.working_tree:
        names = sorted(set(git("ls-files", "--cached", "--others", "--exclude-standard", "-z").decode().split("\0")) - {""})
        names = [n for n in names if (ROOT / n).exists() or (ROOT / n).is_symlink()]
    else:
        names = sorted(set(git("ls-files", "--cached", "-z").decode().split("\0")) - {""})
    for name in names:
        reason = path_problem(name)
        if reason:
            errors.append((name, reason))
            continue
        if args.tree:
            index_path = args.tree + ":" + prefix + name
            size = int(git("cat-file", "-s", index_path))
            read = lambda: git("show", index_path)
        elif args.working_tree:
            path = ROOT / name
            if path.is_symlink():
                errors.append((name, "symlink; target not checked"))
                continue
            size = path.stat().st_size
            read = path.read_bytes
        else:
            stage = git("ls-files", "--stage", "--", name).decode()
            if not stage.startswith("100644 ") and not stage.startswith("100755 "):
                errors.append((name, "non-regular or unmerged index entry"))
                continue
            # Resolve index paths from this pipeline directory even when it is
            # nested inside a larger Git repository (for example data_pipeline/).
            index_path = ":./" + name
            size = int(git("cat-file", "-s", index_path))
            read = lambda: git("show", index_path)
        if size > MAX_SOURCE_BYTES:
            errors.append((name, "source exceeds 2 MiB; review separately"))
            continue
        errors.extend((name, reason) for reason in content_problems(name, read()))
    errors = sorted(set(errors))
    for name, reason in errors:
        print(f"BLOCKED {name}: {reason}")
    if errors:
        print(f"FAILED: {len(errors)} issue(s), {len(names)} pipeline files and {repo_count} repository entries checked. No file contents printed.")
        return 1
    if not names:
        print("No staged files. Use --working-tree to inspect candidates before git add.")
    else:
        label = args.tree or ('working tree' if args.working_tree else 'staged blobs')
        print(f"PASS: {len(names)} pipeline code/configuration files and {repo_count} repository entries checked ({label}).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
